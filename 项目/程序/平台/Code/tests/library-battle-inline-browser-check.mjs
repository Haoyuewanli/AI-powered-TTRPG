import assert from 'node:assert/strict';
import { mkdir, mkdtemp, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { startPlatform } from '../server.mjs';
import { createLibraryStore } from '../library-store.mjs';
import { outputDirectory } from './check-helpers.mjs';
const { chromium } = await import(pathToFileURL(join(process.env.USERPROFILE, '.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright/index.mjs')));
await mkdir(outputDirectory, { recursive: true });
const directory = await mkdtemp(join(outputDirectory, 'library-battle-inline-')), projectRoot = join(directory, '项目');
const module = join(projectRoot, '模组/合成冒险'), run = join(module, '游玩团/run-a');
await mkdir(run, { recursive: true });
await writeFile(join(module, '模组.json'), JSON.stringify({ id: 'module-a', name: '合成冒险' }));
await writeFile(join(run, '团.json'), JSON.stringify({ id: 'run-a', moduleId: 'module-a', name: '合成战斗团', characters: [] }));
const original = await readFile(join(run, '团.json'), 'utf8');
await createLibraryStore({ root: projectRoot }).select({ role: 'dm' }, { moduleId: 'module-a', runId: 'run-a' });
const selected = await readFile(join(run, '团.json'), 'utf8');
const app = await startPlatform({ port: 0, projectRoot, appearanceFile: join(directory, 'appearance.json') });
let browser, page; const errors = [], checks = [], writes = [];
try {
  browser = await chromium.launch({ executablePath: 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', headless: true, args: ['--use-angle=swiftshader-webgl', '--enable-unsafe-swiftshader'] });
  page = await browser.newPage({ viewport: { width: 1540, height: 1020 } }); page.setDefaultTimeout(30000);
  page.on('pageerror', error => errors.push(error.message)); page.on('request', request => { if (request.method() === 'POST') writes.push(new URL(request.url()).pathname); });
  await page.goto(app.url); await page.locator('#enter-dm').click(); await page.getByRole('button', { name: '玩家与角色', exact: true }).waitFor();
  await page.locator('[data-platform-page=battle]').click();
  assert.equal(await page.locator('.p-heading').isVisible(), false);
  assert.equal(await page.locator('[data-project-battle-frame]').count(), 0); assert.equal(writes.filter(path => path === '/api/battle/start').length, 0);
  await page.getByRole('button', { name: '打开本团战斗', exact: true }).click();
  await page.locator('.platform-battle-empty').getByText(/建立本团战斗/).waitFor();
  assert.equal(await page.locator('[data-project-battle-frame]').count(), 0);
  const created = page.waitForResponse(response => new URL(response.url()).pathname === '/api/battle/start' && response.request().method() === 'POST');
  await page.getByRole('button', { name: '建立本团战斗', exact: true }).click();
  const response = await created; assert.equal(response.status(), 200, await response.text());
  const element = page.locator('[data-project-battle-frame]'); await element.waitFor({ state: 'attached' });
  const frame = await (await element.elementHandle()).contentFrame();
  await frame.locator('#enter-dm').click(); await frame.locator('canvas[data-ready=true]').waitFor();
  await page.waitForFunction(() => document.querySelector('[data-project-battle-frame]')?.dataset.ready === 'true');
  assert.equal(await frame.locator('body').getAttribute('data-platform-embedded'), 'true');
  assert.equal(new URL(await element.getAttribute('src')).hostname, '127.0.0.1');
  const box = await element.boundingBox(), workspace = await page.locator('[data-platform-view=battle]').boundingBox();
  assert.ok(box.width >= workspace.width * .95); assert.ok(box.height >= workspace.height * .75);
  await frame.getByRole('button', { name: '添加参战者', exact: true }).click();
  const picker = frame.locator('#add-combatant-dialog');
  await picker.getByLabel('搜索参战者资源', { exact: true }).waitFor();
  await picker.getByLabel('选择参战者资源', { exact: true }).waitFor();
  await frame.waitForFunction(() => !document.getElementById('add-combatant-dialog').hasAttribute('aria-busy'));
  await picker.getByRole('button', { name: '取消', exact: true }).click();
  assert.equal(await readFile(join(run, '团.json'), 'utf8'), selected);
  assert.equal(JSON.parse(original).characters.length, 0);
  checks.push('明确建立本团战斗后嵌入原核心，原团名单不变，DM可用统一＋打开资源选择');
  await page.screenshot({ path: join(directory, 'battle.png') });
  await page.locator('[data-platform-page=home]').click();
  await frame.locator('body[data-platform-visible=false]').waitFor({ state: 'attached' });
  await page.locator('[data-platform-page=battle]').click(); await frame.locator('body[data-platform-visible=true]').waitFor();
  assert.equal(await page.locator('[data-project-battle-frame]').count(), 1);
  checks.push('离开战斗页暂停内嵌核心，返回复用同一画布与存档');
  assert.deepEqual(errors, []); await writeFile(join(directory, 'result.json'), JSON.stringify({ checks, errors }, null, 2));
  for (const check of checks) console.log('通过：' + check); console.log('证据：' + directory);
} catch (error) { await page?.screenshot({ path: join(directory, 'failure.png'), fullPage: true }); console.error('证据：' + directory, errors); throw error; }
finally { await browser?.close(); await app.close(); }
