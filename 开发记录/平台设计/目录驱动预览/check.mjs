import assert from 'node:assert/strict';
import { readFile, mkdir, mkdtemp, writeFile } from 'node:fs/promises';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { createHash } from 'node:crypto';
import { startPreview } from './serve.mjs';

const directory = dirname(fileURLToPath(import.meta.url));
const workspace = resolve(directory, '../../..');
const projectRoot = process.env.RPG_PREVIEW_PROJECT_ROOT || join(workspace, '项目');
const temp = join(workspace, '开发记录/临时');
await mkdir(temp, { recursive: true });
const output = await mkdtemp(join(temp, '目录预览检查-'));
const playwright = process.env.RPG_PLATFORM_PLAYWRIGHT_MODULE || join(process.env.USERPROFILE, '.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright/index.mjs');
const { chromium } = await import(pathToFileURL(playwright));
const app = await startPreview({ projectRoot });
const errors = [], outside = [], requests = [], checks = [];
const coverPath = join(projectRoot, '模组/预处理/故事/stormwreck-isle-v1436/模组封面.png');
const digest = async () => createHash('sha256').update(await readFile(coverPath)).digest('hex');
const before = await digest();
let browser;
try {
  assert.equal((await (await fetch(app.url + '/health')).json()).readOnly, true);
  assert.equal((await fetch(app.url, { method: 'POST', body: '{}' })).status, 405);
  for (const path of ['/api/project', '/AGENTS.md', '/.git/config', '/asset/other', '/serve.mjs']) assert.equal((await fetch(app.url + path)).status, 404);
  checks.push('只读方法及文件白名单');
  browser = await chromium.launch({ executablePath: process.env.RPG_PLATFORM_BROWSER || 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', headless: true });
  const context = await browser.newContext({ viewport: { width: 1600, height: 1050 }, deviceScaleFactor: 1 });
  await context.route('**/*', route => {
    const url = route.request().url();
    if (/^(data:|about:|blob:)/.test(url) || new URL(url).origin === app.url) return route.continue();
    outside.push(url); return route.abort();
  });
  context.on('page', page => {
    page.on('pageerror', error => errors.push(error.message));
    page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
    page.on('request', request => requests.push({ url: request.url(), method: request.method() }));
  });
  const page = await context.newPage();
  page.setDefaultTimeout(8000);
  const click = selector => page.locator(selector).click();
  const nav = value => click('[data-platform-page="' + value + '"]');
  const close = async () => { await click('[data-close-preview]'); await page.locator('dialog.pv-dialog').waitFor({ state: 'hidden' }); };
  await page.goto(app.url);
  await click('#enter-dm');
  await nav('modules');
  assert.deepEqual(await page.locator('[data-group]').allTextContents(), ['单人短团', '多人短团', '长团']);
  assert.equal(await page.locator('[data-ring] img').count() > 0, true);
  await click('[data-group="a"]');
  assert(await page.locator('[data-module-empty]').isVisible());
  await click('[data-group="b"]');
  await click('[data-module-index="0"]');
  const emptyContext = await page.locator('[data-active-campaign]').textContent();
  await click('[data-campaign="friday"]');
  assert.equal(await page.locator('[data-active-campaign]').textContent(), emptyContext);
  await click('[data-continue="friday"]');
  const friday = await page.locator('[data-active-campaign]').textContent();
  assert.notEqual(friday, emptyContext);
  await click('[data-campaign="rehearsal"]');
  assert.equal(await page.locator('[data-active-campaign]').textContent(), friday);
  await page.screenshot({ path: join(output, '模组.png'), fullPage: true });
  checks.push('真实分类名称、空态、概况与继续分开');
  await click('[data-new-campaign]');
  await page.locator('form[data-new-campaign-form] input[name=name]').fill('问卷预览测试团');
  await page.locator('form[data-new-campaign-form] button[type=submit]').click();
  assert.match(await page.locator('.pv-campaigns').textContent(), /问卷预览测试团/);
  checks.push('仅内存新开准备团');
  await nav('resources');
  const search = page.locator('[data-search]');
  await search.fill('guide');
  assert(await page.locator('[data-search-results] [data-open-resource="guide"]').isVisible());
  await click('[data-search-results] [data-open-resource="guide"]');
  assert(await page.locator('dialog.pv-dialog').isVisible());
  assert(await page.locator('dialog.pv-dialog h1, dialog.pv-dialog h2, dialog.pv-dialog h3').count() > 0);
  await click('[data-quote="guide"]');
  await page.locator('[data-view="对话"]:visible').waitFor();
  assert.match(await page.locator('[data-quote-draft]').textContent(), /资源\/NPC\/Y\/.+\/资源.json/);
  checks.push('名称和项目相对链接进入对话演示草稿');
  await nav('resources');
  await search.fill('');
  await click('[data-resource="怪物"]');
  await page.locator('[data-resource-layout][data-phase="open"]').waitFor();
  await click('[data-info-list] [data-open-resource="mist"]');
  await page.screenshot({ path: join(output, '资源阅读.png'), fullPage: true });
  await close();
  await search.fill('没有这条资料');
  assert.match(await page.locator('[data-search-results]').textContent(), /没有匹配/);
  await search.fill('');
  await page.locator('[data-scope]').selectOption('other');
  await search.fill('check');
  assert.match(await page.locator('[data-search-results]').textContent(), /另一演示模组/);
  await page.locator('[data-scope]').selectOption('all');
  await search.fill('');
  await click('[data-folder="resources"]');
  assert.match(await page.locator('dialog.pv-dialog').textContent(), /预览|演示/);
  await close();
  await click('[data-preview-refresh="resources"]');
  checks.push('搜索、模组筛选、卡片展开MD、目标目录和模拟刷新');
  await page.locator('.p-settings').evaluate(node => { node.open = true; });
  assert.equal(await page.locator('[data-color]').count(), 4);
  assert.equal(await page.locator('[data-gradient]').count(), 2);
  for (const preset of ['2560x1600', '2560x1440', '2048x1536', '1920x1440']) await page.locator('select[data-display-preset]').first().selectOption(preset);
  await page.locator('.p-settings').evaluate(node => { node.open = false; });
  checks.push('四布局预设及原外观控件保留（非原生外框验收）');
  await nav('modules');
  await page.setViewportSize({ width: 760, height: 1050 });
  await click('[data-campaign="friday"]');
  await click('[data-continue="friday"]');
  assert(await page.evaluate(() => document.querySelector('.pv-catalog').getBoundingClientRect().bottom <= document.querySelector('.p-footer').getBoundingClientRect().top));
  await page.screenshot({ path: join(output, '窄窗.png'), fullPage: true });
  await page.setViewportSize({ width: 430, height: 900 });
  await nav('resources');
  await search.fill('钥匙');
  await click('[data-search-results] [data-open-resource="key"]');
  await page.screenshot({ path: join(output, '窄窗阅读.png'), fullPage: true });
  await close();
  checks.push('760/430窄窗可继续团及搜索阅读');
  await page.goto(app.url);
  await click('#enter-dm');
  await nav('modules');
  await click('[data-module-index="0"]');
  assert.match(await page.locator('[data-active-campaign]').textContent(), /尚未继续/);
  assert.doesNotMatch(await page.locator('.pv-campaigns').textContent(), /问卷预览测试团/);
  checks.push('刷新页面清空内存演示团及上下文');
  await page.goto(app.url + '/original.html');
  await click('#enter-dm');
  await nav('modules');
  assert.match(await page.locator('[data-group="a"]').textContent(), /分类 A/);
  checks.push('原设计示例独立可访问');
  assert.equal(await digest(), before);
  assert.equal(requests.some(r => r.method !== 'GET' || new URL(r.url).pathname.startsWith('/api/')), false);
  assert.deepEqual(outside, []);
  assert.deepEqual(errors, []);
  checks.push('封面字节未改、无正式API/外部请求、无浏览器错误');
  await writeFile(join(output, 'result.json'), JSON.stringify({ status: 'passed', checks, errors, outside, coverUnchanged: true }, null, 2));
  console.log(JSON.stringify({ output, passed: checks.length }));
} catch (error) {
  await browser?.contexts()[0]?.pages()[0]?.screenshot({ path: join(output, '失败现场.png'), fullPage: true }).catch(() => {});
  await writeFile(join(output, 'result.json'), JSON.stringify({ status: 'failed', checks, errors, outside, error: error.stack }, null, 2));
  console.error(JSON.stringify({ output, checks, errors, error: error.message }));
  throw error;
} finally {
  await browser?.close();
  await app.close();
}
